# ------------------------------------------------------------------
# init-local-mysql.ps1
# Initializes a PRIVATE, project-local MySQL 8 data directory so the
# application can run without an Administrator account and without
# touching any other MySQL installation on the machine.
#
# It only creates:
#   <project>/.mysql/my.ini        -> generated MySQL configuration
#   <project>/.mysql/data/         -> the actual database files
#   <project>/.mysql/logs/         -> the MySQL error log
#
# Re-running the script is safe: if the data directory is already
# initialized it will simply report that and exit.
# ------------------------------------------------------------------
[CmdletBinding()]
param(
    [string] $MysqlHome = "C:\Program Files\MySQL\MySQL Server 8.0",
    [int]    $Port      = 3306
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path (Join-Path $MysqlHome 'bin\mysqld.exe'))) {
    throw "mysqld.exe not found under '$MysqlHome'. Pass -MysqlHome with the correct path."
}

# database/ .. -> project root
$projectRoot = Split-Path -Parent $PSScriptRoot
$mysqlDir    = Join-Path $projectRoot '.mysql'
$dataDir     = Join-Path $mysqlDir    'data'
$logDir      = Join-Path $mysqlDir    'logs'
$myIni       = Join-Path $mysqlDir    'my.ini'

New-Item -ItemType Directory -Force -Path $dataDir, $logDir | Out-Null

$homeFwd = $MysqlHome -replace '\\', '/'
$dataFwd = $dataDir   -replace '\\', '/'
$logFwd  = $logDir    -replace '\\', '/'

$iniContent = @"
# Generated by database/init-local-mysql.ps1 - do not edit by hand.
[mysqld]
basedir="$homeFwd"
datadir="$dataFwd"
port=$Port
bind-address=127.0.0.1
mysqlx=0
character-set-server=utf8mb4
collation-server=utf8mb4_unicode_ci
default-time-zone='+00:00'
sql-mode="ONLY_FULL_GROUP_BY,STRICT_TRANS_TABLES,NO_ZERO_IN_DATE,NO_ZERO_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION"
log-error="$logFwd/mysql-error.log"

[client]
port=$Port
host=127.0.0.1
default-character-set=utf8mb4
"@

Set-Content -Path $myIni -Value $iniContent -Encoding ascii
Write-Host "Wrote MySQL config  -> $myIni"

$systemTables = Join-Path $dataDir 'mysql'
if (-not (Test-Path $systemTables)) {
    Write-Host "Initializing MySQL data directory (this can take ~30 seconds)..."
    & (Join-Path $MysqlHome 'bin\mysqld.exe') --defaults-file="$myIni" --initialize-insecure
    if ($LASTEXITCODE -ne 0) { throw "mysqld --initialize-insecure failed with exit code $LASTEXITCODE" }
    Write-Host "Initialization complete. The 'root' user has an EMPTY password (dev only)."
} else {
    Write-Host "Data directory already initialized - nothing to do."
}

Write-Host ""
Write-Host "Next steps:"
Write-Host "  1) Start MySQL :  database\start-mysql.cmd"
Write-Host "  2) Create DB   :  database\create-and-seed-db.cmd"
